#!/usr/bin/env python3
"""Embed OWASP CRS + virtual @-includes for the modsecurity-proxy-wasm Envoy plugin."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


def raw_cpp_string(data: str, tag: str) -> str:
    # Always use escaped chunks: CRS/setup files contain ')" sequences and '#' lines.
    return c_escaped_concat(data, tag)


def c_escaped_concat(data: str, tag: str) -> str:
    chunk = 12000
    parts = []
    for i in range(0, len(data), chunk):
        piece = data[i : i + chunk]
        esc = (
            piece.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        parts.append(f'"{esc}"')
    if len(parts) == 1:
        return parts[0]
    return "\n    ".join(parts)


CRS_DATA_PREFIX = "@crs-data/"


def wasm_safe_rule_conf(conf: str, rules_dir: Path) -> str:
    """Prepare CRS conf for wasm: keep @pmFromFile (MEMFS), disable @rxFromFile.

    CRS .data phrase lists are embedded under @crs-data/* and written into
    /modsecurity-proxy-wasm-rules at plugin start (see wasm_vfs.cc). ModSecurity
    PmFromFile resolves basenames relative to the rule reference directory, so
    operators stay as ``@pmFromFile scanners-user-agents.data`` etc.
    """
    del rules_dir  # reserved for future path rewrites
    out: list[str] = []
    for line in conf.splitlines():
        stripped = line.lstrip()
        if stripped.startswith("#"):
            out.append(line)
            continue
        if "@rxFromFile" in line:
            out.append("# wasm-disabled (no filesystem): " + line)
            continue
        # Keep @pmFromFile as-is for runtime MEMFS resolution.
        out.append(line)
    return "\n".join(out) + "\n"


def patch_crs_setup(example: str) -> str:
    lines = []
    for line in example.splitlines():
        stripped = line.strip()
        if stripped.startswith("SecAuditLog "):
            lines.append("SecAuditLog /dev/null")
            continue
        if stripped.startswith("SecDebugLog "):
            lines.append("# SecDebugLog disabled in wasm build")
            continue
        if stripped.startswith("SecUnicodeMapFile "):
            lines.append("# SecUnicodeMapFile disabled in wasm build")
            continue
        if stripped.startswith("SecGeoLookupDb "):
            lines.append("# SecGeoLookupDb disabled in wasm build")
            continue
        lines.append(line)
    body = "\n".join(lines)
    header = (
        "# Auto-generated @crs-setup-conf for modsecurity-proxy-wasm (from crs-setup.conf.example)\n"
        "SecRequestBodyAccess On\n"
        "SecResponseBodyAccess On\n"
        "SecAuditEngine Off\n"
    )
    return header + "\n" + body + "\n"


def emit_catalog(assets: list[tuple[str, str]], out_cc: Path, out_h: Path) -> None:
    out_cc.parent.mkdir(parents=True, exist_ok=True)
    entries = []
    body = [
        '// Generated by scripts/generate_rules_catalog.py — do not edit.',
        '#include "generated/rules_catalog.h"',
        '#include <cstring>',
        'namespace modsecurity_proxy_wasm_rules {',
        'namespace {',
    ]
    for idx, (virtual_path, content) in enumerate(assets):
        sym = f"kAsset_{idx}"
        lit = raw_cpp_string(content, sym)
        body.append(f"static const char {sym}[] =\n    {lit};")
        entries.append(
            f'  {{"{virtual_path}", {sym}, sizeof({sym}) - 1}},'
        )
    body.append("static const RuleAsset kCatalog[] = {")
    body.extend(entries)
    body.append("};")
    body.append("static const size_t kCatalogSize = sizeof(kCatalog) / sizeof(kCatalog[0]);")
    body.append("}  // namespace")
    body.append("")
    body.append("const RuleAsset* lookup(const char* path) {")
    body.append("  if (path == nullptr) return nullptr;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append("    if (std::strcmp(kCatalog[i].path, path) == 0) return &kCatalog[i];")
    body.append("  }")
    body.append("  return nullptr;")
    body.append("}")
    body.append("")
    body.append("void foreach_owasp_crs(bool (*fn)(const RuleAsset&, void*), void* user) {")
    body.append("  if (fn == nullptr) return;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append('    const char* p = kCatalog[i].path;')
    body.append('    if (std::strncmp(p, "@owasp_crs/", 11) != 0) continue;')
    body.append("    if (!fn(kCatalog[i], user)) return;")
    body.append("  }")
    body.append("}")
    body.append("")
    body.append("void foreach_crs_data_file(bool (*fn)(const RuleAsset&, void*), void* user) {")
    body.append("  if (fn == nullptr) return;")
    body.append(f'  static const char kDataPrefix[] = "{CRS_DATA_PREFIX}";')
    body.append("  const size_t prefix_len = sizeof(kDataPrefix) - 1;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append("    const char* p = kCatalog[i].path;")
    body.append("    if (std::strncmp(p, kDataPrefix, prefix_len) != 0) continue;")
    body.append("    if (!fn(kCatalog[i], user)) return;")
    body.append("  }")
    body.append("}")
    body.append("")
    body.append("}  // namespace modsecurity_proxy_wasm_rules")
    out_cc.write_text("\n".join(body) + "\n", encoding="utf-8")

    out_h.write_text(
        """// Generated by scripts/generate_rules_catalog.py — do not edit.
#ifndef MODSECURITY_PROXY_WASM_GENERATED_RULES_CATALOG_H_
#define MODSECURITY_PROXY_WASM_GENERATED_RULES_CATALOG_H_

#include <cstddef>

namespace modsecurity_proxy_wasm_rules {

struct RuleAsset {
  const char* path;
  const char* data;
  std::size_t size;
};

const RuleAsset* lookup(const char* path);
void foreach_owasp_crs(bool (*fn)(const RuleAsset&, void*), void* user);
void foreach_crs_data_file(bool (*fn)(const RuleAsset&, void*), void* user);

}  // namespace modsecurity_proxy_wasm_rules

#endif
""",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--crs", type=Path, required=True, help="coreruleset checkout")
    ap.add_argument("--demo", type=Path, required=True, help="demo-conf.conf")
    ap.add_argument("--ftw", type=Path, required=True, help="ftw-config.conf")
    ap.add_argument(
        "--kubewaf-defaults",
        type=Path,
        required=False,
        default=None,
        help="kubewaf-defaults.conf (production baseline for kubeWAF)",
    )
    ap.add_argument("--out-cc", type=Path, default=Path("src/generated/rules_catalog.cc"))
    ap.add_argument("--out-h", type=Path, default=Path("src/generated/rules_catalog.h"))
    args = ap.parse_args()

    crs = args.crs
    rules_dir = crs / "rules"
    if not rules_dir.is_dir():
        print(f"ERROR: missing {rules_dir}", file=sys.stderr)
        return 1

    setup_example = crs / "crs-setup.conf.example"
    if not setup_example.is_file():
        print(f"ERROR: missing {setup_example}", file=sys.stderr)
        return 1

    assets: list[tuple[str, str]] = []
    assets.append(("@demo-conf", args.demo.read_text(encoding="utf-8", errors="replace")))
    assets.append(("@ftw-conf", args.ftw.read_text(encoding="utf-8", errors="replace")))
    kubewaf_defaults = args.kubewaf_defaults
    if kubewaf_defaults is None:
        kubewaf_defaults = args.demo.parent / "kubewaf-defaults.conf"
    if kubewaf_defaults.is_file():
        assets.append(
            ("@kubewaf-defaults", kubewaf_defaults.read_text(encoding="utf-8", errors="replace"))
        )
    assets.append(
        (
            "@crs-setup-conf",
            patch_crs_setup(setup_example.read_text(encoding="utf-8", errors="replace")),
        )
    )

    data_files = sorted(rules_dir.glob("*.data"))
    for path in data_files:
        virtual = f"{CRS_DATA_PREFIX}{path.name}"
        assets.append((virtual, path.read_text(encoding="utf-8", errors="replace")))

    conf_files = sorted(rules_dir.glob("*.conf"))
    if not conf_files:
        print(f"ERROR: no *.conf under {rules_dir}", file=sys.stderr)
        return 1

    all_rules_parts: list[str] = []
    for path in conf_files:
        if path.suffix != ".conf" or ".example" in path.name:
            continue
        virtual = f"@owasp_crs/{path.name}"
        raw = path.read_text(encoding="utf-8", errors="replace")
        safe = wasm_safe_rule_conf(raw, rules_dir)
        assets.append((virtual, safe))
        all_rules_parts.append(f"# --- {path.name} ---\n{safe}")

    # Single bundle for Include @owasp_crs/*.conf (avoids huge runtime concatenation).
    assets.append(("@owasp_crs/_all.conf", "\n".join(all_rules_parts)))

    emit_catalog(assets, args.out_cc, args.out_h)
    total = sum(len(c) for _, c in assets)
    pm_in_rules = sum(
        text.count("@pmFromFile")
        for path, text in assets
        if path.startswith("@owasp_crs/") and path.endswith(".conf")
    )
    print(
        f"Wrote {len(assets)} assets ({len(data_files)} .data, "
        f"{pm_in_rules} @pmFromFile refs) ({total / 1024 / 1024:.2f} MiB) -> {args.out_cc}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())